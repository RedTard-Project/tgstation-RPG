"""Ratwood's player quality of roles for this build: the least PQ a role needs (min_pq) and the round contributor
points it earns (round_contrib_points), for every Rockhill role the porter brought over (rockhill/ported/jobs.dm).

Writes modular_redtard/triumphs/ported/roles.dm: a table by job path that /datum/job/roguetown reads when it is made
(triumphs/roles.dm). A role Ratwood leaves at its defaults (min_pq 0, no points) stays out of the table. The table
names only paths of the ported roles, so a role the porter drops later fails the build instead of coming back as a
stray job; run this again after the porter.

Run from the repository root:  python -I modular_redtard/tools/port_role_pq.py [--ratwood .cache/ratwood]
Reads Ratwood's files only; it never runs git.
"""

import argparse
import os
import re
import sys

OUT = os.path.join('modular_redtard', 'triumphs', 'ported', 'roles.dm')
OURS = os.path.join('modular_redtard', 'rockhill', 'ported', 'jobs.dm')
TYPE_LINE = re.compile(r'^(/datum/job[A-Za-z0-9_/]*)\s*(?://.*)?$')
VAR_LINE = re.compile(r'^\t(min_pq|round_contrib_points|parent_type)\s*=\s*([^/\n]+?)\s*(?://.*)?$')
NUMBER = re.compile(r'^-?\d+(?:\.\d+)?$')
DEFAULTS = {'min_pq': '0', 'round_contrib_points': '0'}


def read_ratwood(root):
    """Job path -> {var: raw value} for every job block of Ratwood's code."""
    jobs = {}
    for folder, _, files in os.walk(root):
        for name in files:
            if not name.endswith('.dm'):
                continue
            current = None
            with open(os.path.join(folder, name), encoding='utf-8', errors='replace') as handle:
                for line in handle:
                    line = line.rstrip('\r\n')
                    if line.lstrip().startswith('//'):
                        continue
                    match = TYPE_LINE.match(line)
                    if match:
                        current = match.group(1)
                        jobs.setdefault(current, {})
                        continue
                    if line and not line.startswith(('\t', ' ')):
                        current = None
                        continue
                    if current:
                        var = VAR_LINE.match(line)
                        if var:
                            jobs[current][var.group(1)] = var.group(2).strip()
    return jobs


def resolve(jobs, path, var):
    """The value a job inherits, walking its parents as DM does."""
    seen = set()
    while path and path not in seen:
        seen.add(path)
        entry = jobs.get(path, {})
        if var in entry:
            return entry[var]
        path = entry.get('parent_type') or path.rsplit('/', 1)[0]
        if path in ('/datum', '/datum/job', ''):
            break
    return DEFAULTS[var]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--ratwood', default=os.path.join('.cache', 'ratwood'))
    args = parser.parse_args()
    if not os.path.isdir(args.ratwood):
        sys.exit(f'No Ratwood tree at {args.ratwood}')
    ours = sorted(set(re.findall(r'^(/datum/job/roguetown/[a-z0-9_/]+)\s*$', open(OURS, encoding='utf-8').read(), re.M)))
    jobs = read_ratwood(args.ratwood)
    rows = []
    skipped = []
    for path in ours:
        if path not in jobs:
            skipped.append(path)
            continue
        min_pq = resolve(jobs, path, 'min_pq')
        points = resolve(jobs, path, 'round_contrib_points')
        if min_pq == 'null':
            min_pq = 'null'
        elif not NUMBER.match(min_pq):
            skipped.append(f'{path} (min_pq {min_pq})')
            continue
        if not NUMBER.match(points):
            points = '0'
        if (min_pq, points) == (DEFAULTS['min_pq'], DEFAULTS['round_contrib_points']):
            continue
        rows.append(f'\t{path} = list({min_pq}, {points}),')
    lines = [
        '// Generated by modular_redtard/tools/port_role_pq.py from Ratwood. Do not edit by hand.',
        '/// Rockhill role -> list(least PQ to take it, null for none; round contributor points), Ratwood\'s min_pq and',
        '/// round_contrib_points. Roles not listed keep Ratwood\'s defaults: PQ 0 and no points.',
        'GLOBAL_LIST_INIT(rogue_role_quality, list(',
        *rows,
        '))',
        '',
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('\n'.join(lines))
    print(f'{len(rows)} roles written to {OUT}; {len(ours) - len(rows) - len(skipped)} at the defaults')
    for path in skipped:
        print(f'not in Ratwood: {path}')


if __name__ == '__main__':
    main()
