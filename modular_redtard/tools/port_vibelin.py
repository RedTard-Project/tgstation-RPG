"""Vibelin's character backgrounds as data for this build: faiths, patrons and cultures (heritage/), from Vibelin's
code/datums/gods and code/datums/culture, and its playable races (port_vibelin_races.py).

The types keep Vibelin's paths (/datum/faith/..., /datum/patron/..., /datum/culture/...): TG has none of them, and
Vibelin's Russian strings (localization/strings/chargen.txt) are keyed by those paths. Only the data is ported (with a
culture's accent, heritage/accents.dm); a patron's prayers, devotion and miracles are Vanderlin's religion system and
stay there. Species ids are Vibelin's
mapped to this build's (VIBELIN_SPECIES_ID): "human" is TG's human, every other race is vib_<id>.

Run from the repository root:  python modular_redtard/tools/port_vibelin.py [--vibelin ../Vibelin]
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import port_rockhill as porter  # noqa: E402  (the porter's DM reader)
import port_vibelin_races  # noqa: E402

OUT = 'modular_redtard/heritage/ported'
ROOTS = {'faith': '/datum/faith', 'patron': '/datum/patron', 'culture': '/datum/culture'}
PATRON_TEXT = ['display_name', 'domain', 'desc', 'worshippers', 'flaws', 'sins', 'boons', 'drawbacks', 'prayer_fail']


def species_id(vibelin_id):
    """This build's id of a Vibelin race."""
    return '"human"' if vibelin_id == 'human' else f'"vib_{vibelin_id}"'


def text(base, path, var):
    raw = base.resolve(path, var)
    if raw is None:
        return None
    value = porter.expand_define(raw.strip())
    value = re.sub(r'\\improper\s*', '', value)
    return value if porter.STRING_LITERAL.match(value) else None


def string_list(base, path, var):
    out = []
    for token in re.findall(r'"(?:[^"\\]|\\.)*"|[A-Z_][A-Z0-9_]*', base.resolve(path, var) or ''):
        value = token if token.startswith('"') else porter.expand_define(token)
        if porter.STRING_LITERAL.match(value):
            out.append(value)
    return out


HIDDEN = set()


def find_hidden(vibelin_root):
    # preference_accessible() overrides whose whole body is "return FALSE": the patron exists but is never picked.
    pattern = re.compile(r'^(/datum/patron/[\w/]+)/preference_accessible\([^)]*\)\s*\n\treturn FALSE\s*$', re.M)
    for folder, _, names in os.walk(os.path.join(vibelin_root, 'code', 'datums', 'gods')):
        for name in names:
            if name.endswith('.dm'):
                HIDDEN.update(pattern.findall(open(os.path.join(folder, name), encoding='utf-8', errors='ignore').read()))


def concrete(base, root):
    for path in sorted(p for p in base.types if p == root or p.startswith(root + '/')):
        if (base.types[path].get('abstract_type') or '').strip().rstrip('/') == path:
            continue
        yield path


DME_FILES = porter.included_files


def module_includes(path):
    """The files an aggregator of Vibelin's modular_abel includes, its own aggregators opened in turn."""
    out = [path]
    folder = os.path.dirname(path)
    for line in open(path, encoding='utf-8', errors='ignore'):
        found = re.match(r'^#include "(.+)"', line.strip())
        if found:
            target = os.path.normpath(os.path.join(folder, found.group(1).replace('\\', '/')))
            out += module_includes(target) if os.path.exists(target) else [target]
    return out


def vibelin_files(code_root):
    """What Vibelin compiles that the port reads: its .dme and its modular races (modular_abel/races)."""
    return DME_FILES(code_root) + module_includes(os.path.join(code_root, 'modular_abel', 'races', '_races.dm'))


def build_defines():
    names = set(porter.tg_defines('code'))
    for folder, _, files in os.walk('modular_redtard'):
        for name in files:
            if name.endswith('.dm'):
                names |= set(re.findall(r'^#define\s+([A-Z0-9_]+)', open(os.path.join(folder, name), encoding='utf-8', errors='ignore').read(), re.M))
    return names


def write(name, blocks):
    os.makedirs(OUT, exist_ok=True)
    path = f'{OUT}/{name}.dm'
    header = f'// Generated by modular_redtard/tools/port_vibelin.py from Vibelin: do not edit by hand.\n\n'
    open(path, 'w', encoding='utf-8', newline='\n').write(header + '\n\n'.join('\n'.join(b) for b in blocks) + '\n')
    print(f'{path}: {len(blocks)} types')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--vibelin', default='../Vibelin')
    args = parser.parse_args()
    if not os.path.exists('tgstation.dme'):
        sys.exit('run from the repository root')
    defines = build_defines()
    print('parsing Vibelin', args.vibelin)
    porter.included_files = vibelin_files
    vibelin = porter.Codebase(porter.parse_codebase(args.vibelin)[0])
    find_hidden(args.vibelin)

    blocks = []
    for path in concrete(vibelin, ROOTS['faith']):
        block = [path]
        for var in ('name', 'desc'):
            value = text(vibelin, path, var)
            if value:
                block.append(f'\t{var} = {value}')
        godhead = (vibelin.resolve(path, 'godhead') or 'null').strip()
        if godhead.startswith('/datum/patron/'):
            block.append(f'\tgodhead = {godhead}')
        blocks.append(block)
    write('faiths', blocks)

    blocks = []
    dropped_traits = set()
    for path in concrete(vibelin, ROOTS['patron']):
        name = text(vibelin, path, 'name')
        if not name:
            continue
        block = [path, f'\tname = {name}']
        for var in PATRON_TEXT:
            value = text(vibelin, path, var)
            if value:
                block.append(f'\t{var} = {value}')
        faith = (vibelin.resolve(path, 'associated_faith') or 'null').strip()
        if faith.startswith('/datum/faith/'):
            block.append(f'\tassociated_faith = {faith}')
        races = [species_id(porter.expand_define(t).strip('"')) for t in re.findall(r'SPEC_ID_[A-Z0-9_]+|"[a-z_]+"', vibelin.resolve(path, 'allowed_races') or '')]
        if races:
            block.append('\tallowed_races = list(' + ', '.join(races) + ')')
        traits = re.findall(r'TRAIT_[A-Z0-9_]+', vibelin.resolve(path, 'added_traits') or '')
        kept = [t for t in traits if t in defines]
        dropped_traits |= set(traits) - set(kept)
        if kept:
            block.append('\trogue_traits = list(' + ', '.join(kept) + ')')
        confess = string_list(vibelin, path, 'confess_lines')
        if confess:
            block.append('\tconfess_lines = list(' + ', '.join(confess) + ')')
        if path in HIDDEN:
            block.append('\trogue_hidden = TRUE')
        blocks.append(block)
    write('patrons', blocks)
    if dropped_traits:
        print('patron traits this build lacks:', ', '.join(sorted(dropped_traits)))

    blocks = []
    accent_names, _ = port_vibelin_races.accent_table(args.vibelin)
    for path in concrete(vibelin, ROOTS['culture']):
        block = [path]
        for var in ('name', 'description', 'pre_append'):
            value = text(vibelin, path, var)
            if value:
                block.append(f'\t{var} = {value}')
        ids = [species_id(porter.expand_define(t).strip('"')) for t in re.findall(r'SPEC_ID_[A-Z0-9_]+|"[a-z_]+"', vibelin.resolve(path, 'species') or '')]
        if ids:
            block.append('\tspecies = list(' + ', '.join(ids) + ')')
        # The accent people of the culture may speak with (heritage/accents.dm).
        accent = accent_names.get((vibelin.resolve(path, 'accent') or '').strip())
        if accent and accent != port_vibelin_races.ACCENT_NONE:
            block.append(f'\trogue_accent = "{accent}"')
        blocks.append(block)
    write('cultures', blocks)

    port_vibelin_races.generate(vibelin, args.vibelin, vibelin_files(args.vibelin), defines)


if __name__ == '__main__':
    main()
