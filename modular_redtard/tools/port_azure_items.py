def main():
    if not os.path.exists(CONFIG) or not os.path.exists(ROCKHILL_CONFIG):
        raise SystemExit('run from the repository root')
    own = json.load(open(CONFIG, encoding='utf-8'))
    picks = set(own['picks'])
    if arg('--lists'):
        build_selection(arg('--lists'), picks)
    if not os.path.exists(SELECTION):
        raise SystemExit(f'{SELECTION} is missing: run once with --lists <K1v lists folder>')
    kinds_wanted = set((arg('--kinds') or ','.join(KINDS)).split(','))
    staged = arg('--staged', STAGED_DEFAULT)
    to_private = '--write-private' in sys.argv

    azure = os.environ.get(own['source'].get('env', ''), '') or own['source']['root']
    if not any(f.endswith('.dme') for f in (os.listdir(azure) if os.path.isdir(azure) else [])):
        raise SystemExit(f"no Azure Peak tree at {azure} (set {own['source'].get('env')})")
    azure = os.path.abspath(azure)

    rcfg = json.load(open(ROCKHILL_CONFIG, encoding='utf-8'))
    cfg = copy.deepcopy(rcfg)
    port = cfg['port']
    tool_prefixes = port['intents'].get('azure', {}).get('items', {}).get('except', [])
    # Only the items and what they shoot; Azure Peak is the source, so its var names are the intents' own.
    port['categories'] = [cat for cat in port['categories'] if cat['file'] in ('items.dm', 'projectiles.dm')]
    for cat in port['categories']:
        # Each type states every inherited var Azure gives it: its DM parent may be a Rockhill type of other values.
        cat['inherited_vars'] = {name: '__k3b_parent__' for name in cat.get('inherited_vars', {})}
    port['intents'].pop('azure', None)
    port['intents']['rename'] = {}
    for key in ('extra_icons', 'extra_sounds', 'extra_files', 'dungeon_templates', 'reskin_vars', 'extra_types'):
        port.pop(key, None)
    port['bake'] = dict(port['bake'], manifest=f'{STAGE}/onmob_bake.json', dir=f'{OUT}/icons/baked')

    # The Ratwood porter, pointed at Azure Peak and at a staging folder; nothing of Rockhill's is written.
    if os.path.isdir(STAGE):
        shutil.rmtree(STAGE)
    os.makedirs(STAGE)
    pr.CHECKOUT = azure
    pr.OUT_DIR = f'{STAGE}/out'
    pr.ICON_DIR = f'{STAGE}/icons'
    pr.SOUND_DIR = f'{STAGE}/sound'
    pr.SMOOTH_DIR = f'{STAGE}/smooth'
    pr.BLANK_WORN = f'{STAGE}/icons/blank_worn.dmi'
    pr.REPORT = f'{STAGE}/report.md'
    pr.OFFLINE = True
    pr.fetch_sources = lambda paths: None
    pr.asset_allowed = lambda rel: True
    pr.write_tables = lambda port: None
    pr.source_maps = lambda cfg, rw=None: []

    print('parsing', azure)
    types, _ = pr.parse_codebase(azure)
    rw = pr.Codebase(types)
    print('azure types:', len(types))
    pr.CONFIG_PORT[0] = port
    declared = pr.declared_paths(pr.DECLARATION_ROOTS, [OUT] + SIBLINGS)
    tg_declared = pr.declared_paths(['code'], [])
    tg_names = pr.tg_defines('code')
    rules = rcfg['replacements']
    rules = [rule for rule in rules if not (rule.get('when_declared') and (rule.get('to') or rule.get('rebase')) not in declared)]

    mine, others = read_selection(picks)
    skipped = OrderedDict()
    chosen = OrderedDict()
    for path, row in mine.items():
        if row['kind'] not in kinds_wanted:
            continue
        reason = excluded(row, own['exclude'])
        if reason is None and path in declared:
            reason = 'the module declares it already'
        if reason is None and pr.replacement_for(path, rules):
            reason = 'the module replaces it (rockhill/config.json replacements)'
        if reason is None and path not in rw.types:
            reason = 'not in the Azure Peak compile'
        if reason is None and pr.category_for(path, port['categories']) is None:
            reason = 'no port category'
        if reason:
            skipped[path] = reason
        else:
            chosen[path] = row
    print('chosen:', len(chosen), 'skipped:', len(skipped))

    pr.generate(cfg, port, rules, rw, declared, tg_declared, tg_names, collections.Counter(), set(chosen), set())
    # Food data (survival module): the Ratwood porter's food part over the kept foods and the module's foods Azure also
    # has (what a food cooks into may be one of them); only the kept foods' blocks and the new recipes stay.
    food_spec = port.get('food')
    food_error = None
    if food_spec and 'food' in kinds_wanted:
        food_spec['file'] = f'{STAGE}/out/food_data.dm'
        staged_types = {b[0] for b in read_blocks(f'{STAGE}/out/items.dm')}
        try:
            pr.generate_food(cfg, rw, staged_types | {p for p in declared - tg_declared if p in rw.types}, tg_declared, tg_names, declared)
        except SystemExit as error:
            food_error = str(error)
            print('food data left out:', food_error)

    # --- keep what the module lacks ---
    out = f'{STAGE}/out'
    item_blocks = read_blocks(f'{out}/items.dm')
    projectile_blocks = read_blocks(f'{out}/projectiles.dm')
    other_build = set(others)
    linked = []

    def keep_type(path):
        if path in chosen:
            return True
        if path in declared or path in tg_declared or path in other_build or path in skipped:
            return False
        if path in mine:
            return False  # a type of the selection left out by --kinds
        linked.append(path)
        return True

    items = [b for b in item_blocks if keep_type(b[0])]
    projectiles = [b for b in projectile_blocks if keep_type(b[0])]
    for block in items:
        if any(pr.boundary_match(block[0], prefix) for prefix in tool_prefixes):
            # Tilling, threshing, digging: the module reads Ratwood's intents, the Rockhill parent's.
            block[:] = [line for line in block if line_var(line) not in INTENT_LISTS]

    rows = {path: OrderedDict(row) for path, row in pr.TABLE_ROWS['items'].items()}
    intent_rows = {path: OrderedDict(row) for path, row in pr.TABLE_ROWS['intents'].items()}

    # Baked held sprites wait for the bake: until a baked sheet holds the state, no held sprite.
    waiting_bake = []
    baked_out = set()
    sheet_names = {}

    def baked_states(sheet):
        if sheet not in sheet_names:
            sheet_names[sheet] = set(dmi.state_names(sheet)) if os.path.exists(sheet) else set()
        return sheet_names[sheet]

    for block in items:
        values = {line_var(l): l.split(' = ', 1)[1] for l in block[1:] if line_var(l)}
        prefix = f"'{OUT}/icons/baked/"
        icon_state = values.get('icon_state', '""').strip('"')
        ready = True
        hands = values.get('lefthand_file', '')
        if hands.startswith(prefix):
            baked_out |= {values[k].strip("'") for k in ('lefthand_file', 'righthand_file') if k in values}
            held = values.get('inhand_icon_state', 'null').strip('"')
            held = icon_state if held == 'null' else held
            ready &= all(held in baked_states(values[k].strip("'")) for k in ('lefthand_file', 'righthand_file') if k in values)
        worn = values.get('rogue_onmob_sheet', '')
        if worn.startswith(prefix):
            baked_out.add(worn.strip("'"))
            name = values.get('rogue_onmob_state', 'null').strip('"')
            name = icon_state if name == 'null' else name
            ready &= any(f'{side}_{name}' in baked_states(worn.strip("'")) for side in ('back', 'hipl'))
        if not ready:
            waiting_bake.append(block[0])
            block[:] = [line for line in block if line_var(line) not in BAKE_VARS]

    # Vars the Rockhill parent sets that an Azure type leaves at the default.
    rockhill = {b[0]: {line_var(l): l for l in b[1:] if line_var(l)} for b in read_blocks(ROCKHILL_ITEMS)}
    item_cat = next(cat for cat in port['categories'] if cat['file'] == 'items.dm')
    resets = dict(RESETS)
    for name in item_cat.get('skip_default', []):
        resets.setdefault(name, '0' if name in item_cat.get('numeric_vars', []) else ('FALSE' if name == 'can_parry' else 'null'))
    for name, value in list(item_cat.get('value_defaults', {}).items()) + [(k, str(v)) for k, v in item_cat.get('numeric_defaults', {}).items()]:
        resets.setdefault(name, value)
    for name in item_cat.get('paths', []) + item_cat.get('path_lists', []) + item_cat.get('grip_lists', []):
        resets.setdefault(name, 'null')
    kept_paths = {b[0] for b in items}
    reset_count = collections.Counter()
    for block in items:
        at = block[0].rsplit('/', 1)[0]
        while at.count('/') >= 2 and at not in kept_paths and at not in rockhill:
            at = at.rsplit('/', 1)[0]
        if at not in rockhill:
            continue
        have = {line_var(l) for l in block[1:]}
        tool = any(pr.boundary_match(block[0], prefix) for prefix in tool_prefixes)
        for name in rockhill[at]:
            if name in have or name not in resets or (tool and name in INTENT_LISTS):
                continue
            if rockhill[at][name].strip() == f'{name} = {resets[name]}':
                continue
            block.append(f'\t{name} = {resets[name]}')
            reset_count[name] += 1

    # An inherited var at its default where nothing above the type (a kept Azure type, a Rockhill one) sets another value:
    # the line is noise (the Ratwood porter leaves it out).
    original_inherited = next(cat for cat in rcfg['port']['categories'] if cat['file'] == 'items.dm').get('inherited_vars', {})
    own_lines = {b[0]: {line_var(l): l.split(' = ', 1)[1] for l in b[1:] if line_var(l)} for b in items}
    trimmed = 0
    for block in sorted(items, key=lambda b: b[0].count('/')):
        drop = set()
        for name, default in original_inherited.items():
            if default is None or own_lines[block[0]].get(name) != str(default):
                continue
            at = block[0].rsplit('/', 1)[0]
            above = None
            while at.count('/') >= 2:
                if at in own_lines:
                    above = own_lines[at].get(name)
                    break
                if at in rockhill:
                    above = rockhill[at][name].split(' = ', 1)[1] if name in rockhill[at] else None
                    break
                at = at.rsplit('/', 1)[0]
            if above in (None, str(default)):
                drop.add(name)
        if drop:
            block[:] = [block[0]] + [l for l in block[1:] if line_var(l) not in drop]
            for name in drop:
                own_lines[block[0]].pop(name, None)
            trimmed += len(drop)
    print('inherited vars at their default left out:', trimmed)

    recipe_root = (food_spec or {}).get('recipe_target', '/datum/rogue_food_recipe')
    food_data = []
    for block in read_blocks(f'{out}/food_data.dm'):
        if block[0] in kept_paths:
            food_data.append(block)
        elif block[0].startswith(recipe_root + '/') and block[0] not in declared:
            result = next((l.split(' = ', 1)[1] for l in block[1:] if line_var(l) == 'result_type'), None)
            if result in kept_paths:
                food_data.append(block)

    # --- datums the kept lines use ---
    intents_all = {b[0]: b for b in read_blocks(f'{out}/intents.dm')}
    grips_all = {b[0]: b for b in read_blocks(f'{out}/alt_grips.dm')}
    storage_all = read_blocks(f'{out}/storage.dm')
    rogue_armor_all = {b[0]: b for b in read_blocks(f'{out}/rogue_armor.dm')}
    tg_armor_all = {b[0]: b for b in read_blocks(f'{out}/armor.dm')}

    def refs(blocks):
        found = set()
        for block in blocks:
            for line in block[1:]:
                found |= set(TYPE_REF.findall(line))
        return found

    used = refs(items + projectiles + food_data)
    grips = [b for p, b in sorted(grips_all.items()) if p in used and p not in declared]
    used |= refs(grips)
    intents = [b for p, b in sorted(intents_all.items()) if p in used and p not in declared]
    used |= refs(intents)
    # An intent sprite the module's HUD sheet lacks: the intent draws its parent's.
    hud = port['intents'].get('icon')
    hud_states = set(dmi.state_names(hud)) if hud and os.path.exists(hud) else None
    hud_dropped = 0
    if hud_states is not None:
        for block in intents:
            for line in list(block[1:]):
                if line_var(line) == 'icon_state' and line.split(' = ', 1)[1].strip('"') not in hud_states:
                    block.remove(line)
                    hud_dropped += 1
    print('intent sprites the HUD sheet lacks:', hud_dropped)
    storage_chain = set().union(*(prefixes(p) for p in used if p.startswith('/datum/storage/'))) if used else set()
    storage = [b for b in storage_all if b[0].split('/New(')[0] in storage_chain and b[0].split('/New(')[0] not in declared]

    # Armor datums: a new one keeps its name; one the module has with other ratings gets an azure_ name.
    module_armor = {}
    for file in ('modular_redtard/rockhill/ported/rogue_armor.dm', 'modular_redtard/rockhill/ported/armor.dm'):
        for b in read_blocks(file):
            module_armor[b[0]] = sorted(l.strip() for l in b[1:])
    renamed = {}
    rogue_armor, tg_armor = [], []
    for table, out_list in ((rogue_armor_all, rogue_armor), (tg_armor_all, tg_armor)):
        for path, block in sorted(table.items()):
            if path not in used:
                continue
            if path in declared:
                if path in module_armor and module_armor[path] != sorted(l.strip() for l in block[1:]):
                    new = path.rsplit('/', 1)[0] + '/azure_' + path.rsplit('/', 1)[1]
                    renamed[path] = new
                    out_list.append([new] + block[1:])
                continue
            out_list.append(block)
    if renamed:
        pattern = re.compile('(' + '|'.join(re.escape(p) for p in sorted(renamed, key=len, reverse=True)) + r')(?![A-Za-z0-9_/])')
        for block in items:
            block[1:] = [pattern.sub(lambda m: renamed[m.group(1)], l) for l in block[1:]]
    armor_rows = {}
    for block in rogue_armor:
        row = OrderedDict()
        kept = [block[0]]
        for line in block[1:]:
            found = pr.TABLE_NUMBER_LINE.match(line)
            if found:
                row[found.group(1)] = found.group(2)
            else:
                kept.append(line)
        block[:] = kept
        if row:
            armor_rows[block[0]] = row

    # --- every path a kept line names must exist ---
    new_types = {b[0] for b in items + projectiles + intents + grips + rogue_armor + tg_armor + food_data} | {b[0] for b in storage if '/New(' not in b[0]}
    valid = declared | tg_declared | set().union(*(prefixes(p) for p in new_types)) if new_types else declared | tg_declared
    dropped_refs = collections.Counter()

    def clean(block):
        out_lines = [block[0]]
        for line in block[1:]:
            bad = [p for p in TYPE_REF.findall(line) if p not in valid]
            if not bad:
                out_lines.append(line)
                continue
            name, sep, value = line.strip().partition(' = ')
            entries = None
            if sep and value.startswith('list(') and value.endswith(')') and '(' not in value[5:-1]:
                entries = [e.strip() for e in value[5:-1].split(',') if e.strip()]
                entries = [e for e in entries if not set(TYPE_REF.findall(e)) & set(bad)]
            for p in bad:
                dropped_refs[f'{name}: {p}'] += 1
            if entries:
                out_lines.append(f'\t{name} = list({", ".join(entries)})')
            elif sep and name == 'possible_item_intents':
                out_lines.append(f'\t{name} = list(/datum/intent/use)')
            elif sep and (value.startswith('list(') or TYPE_REF.fullmatch(value)):
                # Cleared rather than left out: the type would inherit its Rockhill parent's (a steel ingot to smelt into).
                out_lines.append(f'\t{name} = null')
        block[:] = out_lines

    for block in items + projectiles + intents + grips + storage + food_data:
        clean(block)

    # --- sprites and sounds: shared with Rockhill where the file is the same, else copied ---
    copies = {}
    shared = collections.Counter()

    def final_path(staged_rel):
        for stage_root, rock_root, own_root in ((f'{STAGE}/icons', ROCKHILL_ICONS, f'{OUT}/icons'), (f'{STAGE}/sound', ROCKHILL_SOUND, f'{OUT}/sound')):
            if staged_rel.startswith(stage_root + '/'):
                rel = staged_rel[len(stage_root) + 1:]
                rock = f'{rock_root}/{rel}'
                if os.path.exists(rock) and md5(rock) == md5(staged_rel):
                    shared['shared'] += 1
                    return rock
                copies[staged_rel] = f'{own_root}/{rel}'
                return copies[staged_rel]
        return staged_rel

    memo = {}
    asset = re.compile(r"'(" + re.escape(STAGE) + r"/[^']+)'")

    def rewrite(line):
        def sub(m):
            rel = m.group(1)
            if rel == pr.BLANK_WORN:
                return f"'{ROCKHILL_BLANK}'"
            if rel not in memo:
                memo[rel] = final_path(rel)
            return f"'{memo[rel]}'"
        return asset.sub(sub, line)

    all_blocks = items + projectiles + intents + grips + storage + rogue_armor + tg_armor + food_data
    for block in all_blocks:
        block[1:] = [rewrite(l) for l in block[1:]]

    # --- bake manifest: the sheets kept items name, their source sprites at their final places ---
    sheets = []
    for out_sheet, jobs in sorted(pr.BAKE_JOBS.items()):
        if out_sheet not in baked_out:
            continue
        states = []
        for name in sorted(jobs):
            job = dict(jobs[name])
            if job['icon'] not in memo:
                memo[job['icon']] = final_path(job['icon'])
            job['icon'] = memo[job['icon']]
            states.append(job)
        sheets.append({'out': out_sheet, 'states': states})

    # --- Vibelin numbers of the pairs ---
    pairs = {p: r['vibelin_match'] for p, r in chosen.items() if r['vibelin_match'] and p in kept_paths}
    vib_log, vib_changed = vibelin_numbers(own['vibelin'], rows, pairs, {p: r['kind'] for p, r in chosen.items()})

    # --- write ---
    keep_rows = {p: r for p, r in rows.items() if p in kept_paths or p in {b[0] for b in projectiles}}
    keep_intent_rows = {p: r for p, r in intent_rows.items() if p in {b[0] for b in intents}}
    for name in os.listdir(OUT) if os.path.isdir(OUT) else []:
        if name.endswith('.dm'):
            os.remove(os.path.join(OUT, name))
    for folder in ('icons', 'sound'):
        target = f'{OUT}/{folder}'
        if os.path.isdir(target):
            for dp, dn, fn in os.walk(target):
                if os.path.normpath(dp).startswith(os.path.normpath(f'{OUT}/icons/baked')):
                    continue
                for f in fn:
                    os.remove(os.path.join(dp, f))
    os.makedirs(OUT, exist_ok=True)
    by_kind = collections.defaultdict(list)
    kind_of = {}
    for block in items:
        path = block[0]
        kind = chosen[path]['kind'] if path in chosen else ('weapon' if path.startswith(('/obj/item/ammo_casing', '/obj/item/rogueweapon')) else 'other')
        kind_of[path] = kind
        by_kind[kind].append(block)
    files = []
    for kind, file in KIND_FILES.items():
        if by_kind.get(kind):
            write_blocks(f'{OUT}/{file}', by_kind[kind])
            files.append(file)
    for file, blocks in (('food_data.dm', food_data), ('projectiles.dm', projectiles), ('intents.dm', intents), ('alt_grips.dm', grips), ('storage.dm', storage), ('rogue_armor.dm', rogue_armor), ('armor_datums.dm', tg_armor)):
        if blocks:
            write_blocks(f'{OUT}/{file}', blocks)
            files.append(file)
    for src, dest in copies.items():
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        shutil.copyfile(src, dest)
    manifest = {'mask32': port['bake']['mask32'], 'mask64': port['bake']['mask64'], 'canvas': 64, 'sheets': sheets}
    with open(f'{OUT}/onmob_bake.json', 'w', encoding='utf-8', newline='\n') as handle:
        json.dump(manifest, handle, indent='\t', sort_keys=True)
        handle.write('\n')

    tables = rcfg['port']['tables']
    note_items = 'the numbers of the items of modular_redtard/items_azure/ (Azure Peak\'s; Vibelin\'s combat numbers for the Vibelin+Azure pairs), rewritten by tools/port_azure_items.py; an override goes below the end line.'
    note_intents = 'the numbers of the intents of modular_redtard/items_azure/intents.dm (Azure Peak\'s), rewritten by tools/port_azure_items.py.'
    note_armor = 'the ratings of the armor datums of modular_redtard/items_azure/rogue_armor.dm (Azure Peak\'s tiers), rewritten by tools/port_azure_items.py.'
    sections = {
        'items.txt': section_lines(note_items, '/obj/item', keep_rows, list(tables['items']['fields'].values())),
        'intents.txt': section_lines(note_intents, '/datum/intent', keep_intent_rows, list(tables['intents']['fields'].values())),
        'armor.txt': section_lines(note_armor, '/datum/rogue_armor', armor_rows, ['blunt', 'slash', 'stab', 'piercing', 'fire', 'acid', 'magic']),
    }
    if to_private:
        if not os.path.isdir(PRIVATE):
            raise SystemExit(f'{PRIVATE} is missing: mount the private repository first')
        for file, lines in sections.items():
            write_section(os.path.join(PRIVATE, file), lines)
        print('numbers written into', PRIVATE)
    else:
        os.makedirs(staged, exist_ok=True)
        for file, lines in sections.items():
            with open(os.path.join(staged, file), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write('\n'.join(lines) + '\n')
        print('numbers staged in', staged)

    # --- report ---
    with open(f'{CACHE}/vibelin_numbers.tsv', 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('type\tvibelin\tfield\tazure\tvibelin_value\ttaken\n')
        for r in vib_log:
            handle.write('\t'.join(str(x) for x in r) + '\n')
    with open(REPORT, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('# Ported Azure Peak items\n\n')
        handle.write('Generated by `modular_redtard/tools/port_azure_items.py` (task K3b) from the Azure Peak code tree with the conversion of the Ratwood porter. ')
        handle.write('Each type keeps its Azure Peak path; its balance numbers are in the `port_azure_items.py` section of the private `items.txt` (intents: `intents.txt`, armor datums: `armor.txt`).\n\n')
        handle.write('| Kind | Ported | Skipped |\n|---|---|---|\n')
        skip_kind = collections.Counter(mine[p]['kind'] for p in skipped)
        for kind in KINDS:
            handle.write(f'| {kind} | {len(by_kind.get(kind, []))} | {skip_kind.get(kind, 0)} |\n')
        handle.write(f'\nAlso: {len(projectiles)} projectiles, {len(intents)} intents, {len(grips)} alternate grips, {len(rogue_armor)} armor datums, {len(tg_armor)} TG armor datums, {len([b for b in storage if "/New(" not in b[0]])} grid storages. ')
        handle.write(f'Types pulled in by links (what an arrow shoots and the like): {len(linked)}. Held sprites waiting for the bake: {len(waiting_bake)}. Food data blocks and recipes: {len(food_data)}.\n\n')
        if food_error:
            handle.write(f'Food data left out: {food_error}\n\n')
        for kind in KINDS:
            blocks = by_kind.get(kind, [])
            if not blocks:
                continue
            handle.write(f'## {kind} ({len(blocks)})\n\n')
            for block in blocks:
                name = next((l.split(' = ', 1)[1] for l in block[1:] if line_var(l) == 'name'), '')
                handle.write(f'- `{block[0]}` {name}\n')
            handle.write('\n')
        handle.write(f'## Skipped ({len(skipped)})\n\n| Type | Kind | Reason |\n|---|---|---|\n')
        for path, reason in sorted(skipped.items(), key=lambda kv: (kv[1], kv[0])):
            handle.write(f"| `{path}` | {mine[path]['kind']} | {reason} |\n")
        if dropped_refs:
            handle.write(f'\n## Lines left out: the path they name is not in the module ({sum(dropped_refs.values())})\n\n')
            for key, n in dropped_refs.most_common():
                handle.write(f'- `{key}` ({n})\n')
        if waiting_bake:
            handle.write(f'\n## Held sprites waiting for the bake ({len(waiting_bake)})\n\n')
            for path in waiting_bake:
                handle.write(f'- `{path}`\n')

    print('files:', ', '.join(files))
    print('kinds:', ', '.join(f'{k} {len(v)}' for k, v in by_kind.items()), '| projectiles', len(projectiles), '| intents', len(intents), '| grips', len(grips), '| storage', len(storage), '| armor', len(rogue_armor), '+', len(tg_armor), '(renamed', len(renamed), ')')
    print('linked types:', len(linked), '| resets:', sum(reset_count.values()), dict(reset_count.most_common(8)))
    print('waiting for the bake:', len(waiting_bake), '| bake sheets:', len(sheets), 'states:', sum(len(s['states']) for s in sheets))
    print('assets: copied', len(copies), 'bytes', sum(os.path.getsize(s) for s in copies), '| shared with Rockhill', len({k for k, v in memo.items() if v.startswith(('modular_redtard/rockhill/'))}))
    print('dropped refs:', sum(dropped_refs.values()), dict(dropped_refs.most_common(6)))
    print('vibelin pairs:', len(pairs), 'numbers changed:', vib_changed)
    print('table rows: items', len(keep_rows), 'intents', len(keep_intent_rows), 'armor', len(armor_rows))
    print('report:', REPORT)


