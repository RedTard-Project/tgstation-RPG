def build_selection(lists, picks):
    dups = {r['type']: r for r in csv.DictReader(open(os.path.join(lists, 'duplicates.tsv'), encoding='utf-8'), delimiter='\t')}
    rows = []
    for r in csv.DictReader(open(os.path.join(lists, 'missing_azure.tsv'), encoding='utf-8'), delimiter='\t'):
        d = dups.get(r['type'])
        pick = d['pick'] if d else 'azure'
        if pick not in picks:
            continue
        rows.append({'type': r['type'], 'kind': r['kind'], 'name': r['name'], 'file': r['file'], 'pick': pick, 'vibelin_match': (d or {}).get('vibelin_match', '') if pick != 'azure' else ''})
    others = sorted(t for t, d in dups.items() if d['pick'] not in picks)
    os.makedirs(OUT, exist_ok=True)
    with open(SELECTION, 'w', encoding='utf-8', newline='\n') as out:
        out.write('# The Azure Peak item types K3b ports (tools/port_azure_items.py --lists rebuilds this file from the K1v inventory).\n')
        out.write('# "other" rows are types another build ports (their pick in duplicates.tsv): never generated here.\n')
        out.write('type\tkind\tname\tfile\tpick\tvibelin_match\n')
        for r in sorted(rows, key=lambda r: r['type']):
            out.write('\t'.join(r[k] for k in ('type', 'kind', 'name', 'file', 'pick', 'vibelin_match')) + '\n')
        for t in others:
            out.write(f"{t}\tother\t\t\t{dups[t]['pick']}\t\n")
    print('selection:', len(rows), 'types,', len(others), 'types of other builds ->', SELECTION)


def read_selection(picks):
    mine, others = OrderedDict(), {}
    for line in open(SELECTION, encoding='utf-8'):
        if line.startswith('#') or line.startswith('type\t'):
            continue
        parts = line.rstrip('\n').split('\t')
        if len(parts) < 6:
            continue
        row = dict(zip(('type', 'kind', 'name', 'file', 'pick', 'vibelin_match'), parts))
        if row['pick'] in picks:
            mine[row['type']] = row
        else:
            others[row['type']] = row['pick']
    return mine, others


def excluded(row, rules):
    for rule in rules:
        if 'match' in rule and re.search(rule['match'], row['type']):
            return rule['reason']
        if 'prefix' in rule and pr.boundary_match(row['type'], rule['prefix']):
            return rule['reason']
        if 'file' in rule and (row['file'] == rule['file'] or (rule['file'].endswith('/') and row['file'].startswith(rule['file']))):
            return rule['reason']
    return None


# --- Vibelin numbers --------------------------------------------------------------------------------------------------

class Vibelin:
    def __init__(self, spec):
        sys.path.insert(0, spec['dm_type_port'])
        import dm_type_port as dtp
        root = os.environ.get(spec.get('env', ''), '') or spec['root']
        cache = f'{CACHE}/vibelin.pickle'
        stamp = os.path.getmtime(os.path.join(root, spec['dme'])) if os.path.exists(os.path.join(root, spec['dme'])) else None
        data = None
        if os.path.exists(cache):
            with open(cache, 'rb') as f:
                data = pickle.load(f)
            if data.get('stamp') != stamp:
                data = None
        if data is None:
            if stamp is None:
                raise SystemExit(f"no Vibelin tree at {root} (set {spec.get('env')})")
            types, defines, _ = dtp.parse(dtp.compiled_files(root, spec['dme']))
            data = {'stamp': stamp, 'types': dict(types), 'defines': defines}
            os.makedirs(CACHE, exist_ok=True)
            with open(cache, 'wb') as f:
                pickle.dump(data, f)
        self.types, self.defines = data['types'], data['defines']
        self.src = dtp.Source(self.types, self.defines)

    def origin(self, path, var):
        seen = set()
        while path and path not in seen:
            seen.add(path)
            if var in self.types.get(path, {}):
                return path
            path = self.src.parent(path)
        return None

    def evaluate(self, text, depth=0):
        if text is None or depth > 12:
            return None
        text = text.strip()
        if text == 'TRUE':
            return 1
        if text in ('FALSE', 'null'):
            return 0

        def sub(m):
            tok = m.group(0)
            if tok in UNITS:
                return UNITS[tok]
            if tok in self.defines:
                val = self.evaluate(self.defines[tok], depth + 1)
                if val is None:
                    raise ValueError(tok)
                return '(' + repr(val) + ')'
            raise ValueError(tok)
        try:
            expr = TOKEN.sub(sub, text)
        except ValueError:
            return None
        if not SAFE.match(expr):
            return None
        try:
            val = eval(expr, {'__builtins__': {}}, {})
        except Exception:
            return None
        if isinstance(val, float):
            val = int(val) if val.is_integer() else round(val, 4)
        return val

    def value(self, path, var):
        if self.origin(path, var) in VIBELIN_ROOTS:
            return None
        return self.evaluate(self.src.resolve(path, var))


def fmt(v):
    if isinstance(v, float):
        return f'{v:.4f}'.rstrip('0').rstrip('.')
    return str(v)


def vibelin_numbers(spec, rows, pairs, kinds):
    """K2g's rules: force, force_wielded, throw_force, defense from Vibelin; integrity from Vibelin on armor only (its
    weapon integrity has a scale of its own); min_strength where Vibelin sets one; penetration and the wielded defense
    bonus stay Azure's (Vibelin counts percent points, has no bonus)."""
    if not pairs:
        return [], 0
    vib = Vibelin(spec)
    skip = re.compile(spec['exclude'])
    log = []
    changed = 0
    for path, match in sorted(pairs.items()):
        oid = path[len('/obj/item/'):]
        if kinds[path] not in spec['kinds'] or skip.match(oid):
            continue
        if match not in vib.types:
            log.append((path, match, '-', '', '', 'no Vibelin type'))
            continue
        weapon = kinds[path] == 'weapon' or oid.startswith(('rogueweapon/', 'gun/', 'ammo_casing/'))
        row = rows.setdefault(path, OrderedDict())
        for field, var in VIBELIN_FIELDS.items():
            ours = row.get(field)
            vv = vib.value(match, var)
            if field in ('force_wielded', 'min_strength') and not vv:
                vv = None
            if field == 'unarmed_bonus' and vv == 1 and ours is None:
                vv = None
            if field == 'integrity' and weapon:
                vv = None
            if vv is None or (ours is None and vv == 0):
                continue
            log.append((path, match, field, ours or '', fmt(vv), 'vibelin'))
            if ours is None or float(ours) != float(vv):
                row[field] = fmt(vv)
                changed += 1
    return log, changed


