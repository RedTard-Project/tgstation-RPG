"""Port Azure Peak's items the module lacks (block K3, task K3b) into modular_redtard/items_azure/.

The selection comes from the K1v inventory of the four builds (duplicates.tsv, missing_azure.tsv): every item type the
module does not have whose pick is Azure Peak ("azure", or "vibelin(numbers)+azure(intents)": Azure's type and
intents, Vibelin's combat numbers). It is kept in items_azure/selection.tsv, so a run needs only that file and the
Azure Peak tree; --lists <dir> rebuilds it from a newer inventory.

The conversion is the Ratwood porter's (tools/port_rockhill.py, called, never changed): its items and projectiles
categories run over Azure Peak's code tree in a staging folder, and this tool keeps what the module does not declare
yet, checks every path a kept line names, splits the items by kind and copies the sprites and sounds they use
(a file Rockhill already holds byte for byte is shared). Weapons keep Azure's intents (Azure is the source); a tool
whose work the module reads from Ratwood's intents (port.intents.azure.items.except of rockhill/config.json) inherits
them from its Rockhill parent instead.

Balance numbers never stay in the types: the items' (port.tables.items of rockhill/config.json), the new intents' and
the new armor datums' numbers go to sections "# >>> port_azure_items.py" ... "# <<< port_azure_items.py" of
items.txt, intents.txt and armor.txt: by default staged in the K3 work folder (--staged), with --write-private
straight into config/redtard_private/mechanics/, below the Rockhill porter's section.

Held sprites of Azure's experimental_inhand items are baked like Rockhill's: the manifest is items_azure/onmob_bake.json
(ai-skills bake_onmob_sheets.py); until a baked sheet holds the state, the item is written without a held sprite. Run
the tool again after a bake.

    py -3 modular_redtard/tools/port_azure_items.py [--kinds weapon,armor,...] [--lists <dir>] [--staged <dir>] [--write-private]

Run from the repository root. Read only on Azure Peak and Vibelin (no git there).
"""

