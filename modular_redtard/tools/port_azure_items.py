def md5(path):
    with open(path, 'rb') as f:
        return hashlib.md5(f.read()).hexdigest()


def read_blocks(path):
    """The blocks of a generated .dm file: a line at column 0 opens a block, the indented lines below it are its."""
    blocks = []
    if not os.path.exists(path):
        return blocks
    for line in open(path, encoding='utf-8').read().split('\n'):
        if not line.strip():
            continue
        if not line.startswith(('\t', ' ')):
            blocks.append([line])
        elif blocks:
            blocks[-1].append(line)
    return blocks


def write_blocks(path, blocks):
    text = HEADER + '\n\n' + '\n\n'.join('\n'.join(b) for b in blocks) + '\n'
    with open(path, 'w', encoding='utf-8', newline='\n') as out:
        out.write(text)


def line_var(line):
    name, sep, _ = line.strip().partition(' = ')
    return name if sep and line.startswith('\t') and not line.startswith('\t\t') else None


def prefixes(path):
    parts = path.split('/')
    return {'/'.join(parts[:k]) for k in range(3, len(parts) + 1)}


