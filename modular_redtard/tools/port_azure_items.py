def section_lines(note, root, rows, order):
    lines = [f'# >>> {SECTION}: {note}', '']
    for path in sorted(rows):
        row = rows[path]
        if not row:
            continue
        lines.append(f'[{path[len(root) + 1:]}]')
        lines += [f'{field} = {row[field]}' for field in sorted(row, key=lambda f: order.index(f) if f in order else len(order))]
        lines.append('')
    lines.append(f'# <<< {SECTION}')
    return lines


def write_section(target, lines, after='# <<< port_rockhill.py'):
    """The section into a private table: replaced where it stands, else right below the Rockhill porter's section."""
    text = open(target, encoding='utf-8').read().replace('\r\n', '\n') if os.path.exists(target) else ''
    block = '\n'.join(lines) + '\n'
    pattern = re.compile(rf'^# >>> {re.escape(SECTION)}.*?^# <<< {re.escape(SECTION)}\n', re.S | re.M)
    if pattern.search(text):
        text = pattern.sub(lambda m: block, text)
    elif after in text:
        at = text.index(after) + len(after)
        at = text.index('\n', at) + 1 if '\n' in text[at:] else len(text)
        text = text[:at] + '\n' + block + text[at:]
    else:
        text = text.rstrip('\n') + '\n\n' + block
    with open(target, 'w', encoding='utf-8', newline='\n') as out:
        out.write(text)


